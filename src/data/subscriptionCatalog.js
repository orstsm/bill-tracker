export const normalizeSubscriptionName = (value = '') => value
  .toLowerCase()
  .normalize('NFKD')
  .replace(/[^a-z0-9]/g, '');

export function findSubscription(value = '') {
  const key = normalizeSubscriptionName(value);
  if (!key) return null;

  return SUBSCRIPTION_CATALOG.find((subscription) => (
    normalizeSubscriptionName(subscription.name) === key
    || subscription.aliases.some((alias) => normalizeSubscriptionName(alias) === key)
  )) || null;
}

export function searchSubscriptions(query = '') {
  const key = normalizeSubscriptionName(query);
  if (!key) return SUBSCRIPTION_CATALOG;

  return SUBSCRIPTION_CATALOG.filter((subscription) => {
    const searchable = [subscription.name, subscription.category, ...subscription.aliases]
      .map(normalizeSubscriptionName);
    return searchable.some((value) => (
      key.length <= 2 ? value === key || value.startsWith(key) : value.includes(key)
    ));
  });
}
